#!/usr/bin/env python3
"""Generate deterministic texzi fixtures with Python 3.10+ standard library.

No editor or benchmark is run. The default smoke profile writes about 2 MiB plus
small correctness inputs. Standard writes about 443 MiB; stress adds two 100 MiB
long-line inputs. Generated samples belong outside the design deliverable ZIP.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import re
from pathlib import Path
from typing import Callable, Iterator


VERSION = "1.0.0"
MIB = 1024 * 1024
KIB = 1024
DEFAULT_SEED = 20261115
EOL_RE = re.compile(r"(\r\n|\r|\n)")
NOT_IMPLEMENTED = [
    "MD-COMPLEX: deep nesting, giant tables and parser-derived structure counts",
    "HUGE-1G: 1 GiB inputs are not generated by this version",
    "THRESHOLD: exact 20/200 MiB +/-1 byte and 19999/20000/20001 scalar cases",
    "IMAGE: local image decoding and remote-resource timing fixtures",
    "Windows app, ETW/PresentMon runner, hardware/IME automation and measurements",
]


class Lcg32:
    """Specified arithmetic, independent of Python's random implementation."""

    def __init__(self, seed: int):
        self.state = seed & 0xFFFFFFFF

    def next(self) -> int:
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state


class LineStats:
    """Logical lines use CRLF/LF/CR only; a trailing EOL creates an empty line."""

    def __init__(self, encoding: str):
        self.encoding = encoding
        self.breaks = 0
        self.current_bytes = 0
        self.current_scalars = 0
        self.max_bytes = 0
        self.max_scalars = 0
        self.pending_cr = False
        self.eols = {"CRLF": 0, "LF": 0, "CR": 0}

    def feed(self, text: str) -> None:
        if not text:
            return
        if self.pending_cr:
            if text.startswith("\n"):
                self.eols["CR"] -= 1
                self.eols["CRLF"] += 1
                text = text[1:]
            self.pending_cr = False
        parts = EOL_RE.split(text)
        for i, part in enumerate(parts):
            if i % 2 == 0:
                self.current_bytes += len(part.encode(self.encoding, "strict"))
                self.current_scalars += len(part)
                self.max_bytes = max(self.max_bytes, self.current_bytes)
                self.max_scalars = max(self.max_scalars, self.current_scalars)
            else:
                self.breaks += 1
                self.eols[{"\r\n": "CRLF", "\n": "LF", "\r": "CR"}[part]] += 1
                self.current_bytes = 0
                self.current_scalars = 0
                self.pending_cr = part == "\r" and i == len(parts) - 2

    def result(self) -> dict:
        return {
            "line_count": self.breaks + 1,
            "line_count_definition": "CRLF/LF/CR delimiters + 1; trailing empty line included",
            "max_line_bytes": self.max_bytes,
            "max_line_unicode_scalars": self.max_scalars,
            "line_endings": self.eols,
            "line_lengths_exclude": "BOM and line-ending bytes",
        }


class FixtureWriter:
    def __init__(self, path: Path, encoding: str = "utf-8", bom: bytes = b""):
        self.path = path
        self.temp = path.with_name(path.name + ".tmp")
        self.encoding = encoding
        self.bom = bom
        self.hasher = hashlib.sha256()
        self.size = 0
        self.tail_padding_bytes = 0
        self.stats = LineStats(encoding)
        self.file = self.temp.open("wb")
        self._write_bytes(bom)

    def _write_bytes(self, data: bytes) -> None:
        self.file.write(data)
        self.hasher.update(data)
        self.size += len(data)

    def write_text(self, text: str) -> None:
        data = text.encode(self.encoding, "strict")
        self._write_bytes(data)
        self.stats.feed(text)

    def finish(self) -> dict:
        self.file.close()
        os.replace(self.temp, self.path)
        return {
            "size_bytes": self.size,
            "sha256": self.hasher.hexdigest(),
            "encoding": self.encoding,
            "expected_strict_decode_valid": True,
            "bom_hex": self.bom.hex(),
            "bom_bytes": len(self.bom),
            **self.stats.result(),
        }

    def abort(self) -> None:
        self.file.close()
        self.temp.unlink(missing_ok=True)


def fill_exact(writer: FixtureWriter, target: int, records: Iterator[str], *, tail_width: int | None = None) -> int:
    """Write whole UTF-8 records, then ASCII padding; never cut a code point.

    Padding is at most one record's length. Markdown records end after closed
    blocks, so the tail is a plain paragraph, never a partially written fence.
    """
    if writer.encoding != "utf-8" or writer.bom:
        raise ValueError("exact-size generation expects UTF-8 without BOM")
    remaining = target
    buffered: list[str] = []
    buffer_bytes = 0
    count = 0
    for record in records:
        size = len(record.encode("utf-8"))
        if size > remaining:
            break
        buffered.append(record)
        buffer_bytes += size
        remaining -= size
        count += 1
        if buffer_bytes >= 64 * KIB:
            writer.write_text("".join(buffered))
            buffered.clear()
            buffer_bytes = 0
        if remaining == 0:
            break
    if buffered:
        writer.write_text("".join(buffered))
    writer.tail_padding_bytes = remaining
    if tail_width is not None:
        while remaining >= tail_width:
            writer.write_text("x" * (tail_width - 1) + "\n")
            remaining -= tail_width
    while remaining:
        n = min(remaining, 64 * KIB)
        writer.write_text("x" * n)
        remaining -= n
    if writer.size != target:
        raise AssertionError(f"wrong size: {writer.size} != {target}")
    return count


def plain_records(seed: int, ascii_only: bool = False) -> Iterator[str]:
    rng = Lcg32(seed)
    i = 0
    phrases = [
        "整理今日记录，确认下一步安排，保留讨论中的问题与结论。编辑时保持文字原貌，检查标点、空白和换行，完成后再保存。",
        "项目笔记用于日常文字管理，可以记录想法、清单和代码片段。中文输入需要连续自然，切换文件后仍能回到原来的位置。",
        "本段用于生成可重复的性能样本，内容不对应真实人员或事件。每行包含不同编号，方便检查搜索、滚动和文件尾部定位。",
    ]
    while True:
        token = rng.next()
        if ascii_only:
            yield (
                f"{i:08d} INFO item={token:08x} action=update status=ready "
                "path=notes/example.txt preserve whitespace and line endings; next step pending.\n"
            )
        else:
            sep = "\t" if i % 13 == 0 else " "
            yield f"{i:08d}{sep}{phrases[token % len(phrases)]} code={token:08x} note=ready\r\n"
        i += 1


def markdown_section(index: int, token: int) -> str:
    paragraph = "\n".join(
        f"第{j:02d}行：这是可直接编辑的日常记录，包含中文、English和数字{token:08x}。"
        "阅读与编辑使用同一份原文，保留空格、标点及段落结构；检查滚动位置和输入响应。"
        for j in range(48)
    )
    return (
        f"## 第 {index:06d} 节：日常记录\n\n"
        f"{paragraph}\n\n"
        "> 引用保留来源说明。\n> 第二行用于跨行选择。\n\n"
        "- [ ] 整理笔记\n- [x] 核对条目\n- [ ] 保存结果\n\n"
        "```python\n"
        f"item = {token}\n"
        "def describe(value):\n    return f'item={value}'\n"
        "```\n\n"
        "| 项目 | 状态 | 数量 |\n| :--- | :---: | ---: |\n"
        "| 笔记 | 进行中 | 12 |\n| 片段 | 已保存 | 7 |\n| 清单 | 待检查 | 3 |\n\n"
        "查看[本地说明](./README.md)，以及 **重点**、*补充*、~~旧项~~和`value`。\n\n"
    )


def markdown_records(seed: int) -> Iterator[str]:
    rng = Lcg32(seed)
    i = 0
    while True:
        yield markdown_section(i, rng.next())
        i += 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", choices=("smoke", "standard", "stress"), default="smoke")
    parser.add_argument("--manifest", type=Path, default=Path("fixtures/manifest.json"))
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()
    manifest_path = args.manifest.expanduser().resolve()
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    sample_dir = manifest_path.parent / "texzi-fixtures"
    sample_dir.mkdir(parents=True, exist_ok=True)
    files: list[dict] = []

    def text_fixture(
        fixture_id: str,
        suffix: str,
        produce: Callable[[FixtureWriter], dict],
        *,
        encoding: str = "utf-8",
        bom: bytes = b"",
        category: str,
        seed_dependent: bool = False,
    ) -> None:
        path = sample_dir / (fixture_id + suffix)
        writer = FixtureWriter(path, encoding, bom)
        try:
            metadata = produce(writer)
            record = writer.finish()
        except BaseException:
            writer.abort()
            raise
        files.append({
            "id": fixture_id,
            "path": path.relative_to(manifest_path.parent).as_posix(),
            "category": category,
            "seed_dependent": seed_dependent,
            **record,
            "structure": metadata,
        })

    def small(fixture_id: str, text: str, *, encoding: str = "utf-8", bom: bytes = b"", metadata: dict | None = None, suffix: str = ".txt") -> None:
        def produce(writer: FixtureWriter) -> dict:
            writer.write_text(text)
            return metadata or {}
        text_fixture(fixture_id, suffix, produce, encoding=encoding, bom=bom, category="correctness")

    def sized_text(fixture_id: str, size: int, ascii_only: bool = False) -> None:
        def produce(writer: FixtureWriter) -> dict:
            count = fill_exact(writer, size, plain_records(args.seed, ascii_only))
            return {"exact_target_bytes": size, "complete_records": count, "content": "ASCII log" if ascii_only else "CJK/Latin/numbers/tab mixed"}
        text_fixture(fixture_id, ".txt", produce, category="normal-text", seed_dependent=True)

    def sized_md(fixture_id: str, size: int) -> None:
        def produce(writer: FixtureWriter) -> dict:
            count = fill_exact(writer, size, markdown_records(args.seed), tail_width=256)
            section = markdown_section(0, Lcg32(args.seed).next())
            paragraph = section.split("\n\n")[1]
            return {
                "exact_target_bytes": size,
                "complete_sections": count,
                "generated_top_level_blocks": count * 7 + int(writer.tail_padding_bytes > 0),
                "structural_node_upper_bound_estimate": count * 40 + 1,
                "max_generated_paragraph_utf8_bytes": max(len(paragraph.encode("utf-8")), writer.tail_padding_bytes),
                "max_table_cells": 12,
                "total_generated_table_cells": count * 12,
                "fenced_code_blocks": count,
                "network_resources": False,
                "structure_counts_source": "known generator template; actual parser-derived counts not measured",
            }
        text_fixture(fixture_id, ".md", produce, category="normal-markdown", seed_dependent=True)

    def sized_long(fixture_id: str, size: int) -> None:
        def records() -> Iterator[str]:
            rng = Lcg32(args.seed)
            while True:
                yield "LONG_" + "_".join(f"{rng.next():08x}" for _ in range(28))
        def produce(writer: FixtureWriter) -> dict:
            fill_exact(writer, size, records())
            return {"exact_target_bytes": size, "expected_line_count": 1, "expected_max_line_unicode_scalars": size}
        text_fixture(fixture_id, ".txt", produce, category="long-line", seed_dependent=True)

    def sized_matches(fixture_id: str, size: int) -> None:
        def records() -> Iterator[str]:
            rng = Lcg32(args.seed)
            while True:
                yield f"needle:{rng.next():08x}\n"
        def produce(writer: FixtureWriter) -> dict:
            count = fill_exact(writer, size, records())
            return {"exact_target_bytes": size, "literal_query": "needle", "expected_literal_matches": count, "record_bytes": 16}
        text_fixture(fixture_id, ".txt", produce, category="high-match-count", seed_dependent=True)

    sized_text("TXT-1", MIB)
    sized_md("MD-1", MIB)
    sized_long("LONG-100K", 100 * KIB)
    sized_matches("MATCH-HIGH-SMOKE", 64 * KIB)

    unicode_text = "中文与English\r\n组合重音：e\u0301；家庭：👨‍👩‍👧‍👦；肤色：👍🏽\n扩展汉字：𠮷；旗帜：🏳️‍🌈；制表\t对齐\r末行无换行"
    small("UNICODE", unicode_text, metadata={"contains": ["combining mark", "ZWJ emoji", "skin tone modifier", "supplementary CJK", "tab"], "no_final_newline": True})
    small("EOL-MIXED", "第一行\r\nsecond line\n第三行\r第四行\r\nfinal", metadata={"expected_eols": {"CRLF": 2, "LF": 1, "CR": 1}, "dominant_eol": "CRLF", "no_final_newline": True})
    small("EOL-TIE", "first\nsecond\r\nlast", metadata={"expected_eols": {"CRLF": 1, "LF": 1, "CR": 0}, "tie_break_first_eol": "LF"})
    small("MD-FIDELITY", "Title\r\n=====\r\n\r\n* one  \r\n* **two**\n\n[ref]: ./local.md \"title\"\n\n[link][ref]\n\n<custom data-x='keep'>原样</custom>\n\n[^unknown]: footnote extension\rfinal", metadata={"purpose": "source preservation, unknown syntax, mixed EOL, exact whitespace"}, suffix=".md")

    common = "中文 English 123\r\n编码测试：€、𠮷、🙂\n末行"
    small("ENC-UTF8-BOM", common, bom=b"\xef\xbb\xbf")
    small("ENC-UTF16LE", common, encoding="utf-16-le", bom=b"\xff\xfe")
    small("ENC-UTF16BE", common, encoding="utf-16-be", bom=b"\xfe\xff")
    small("ENC-GB18030", common, encoding="gb18030", metadata={"codec_mapping": "Python runtime gb18030 codec; GB18030 standard revision not asserted"})
    small("ENC-GBK", "中文 English 123\r\n编码测试与原样保存\n末行", encoding="gbk", metadata={"code_page": 936, "unrepresentable_probe": "🙂"})
    small("ENC-1252", "café naïve € — \"quoted\"\r\nlast line", encoding="cp1252", metadata={"code_page": 1252, "unrepresentable_probe": "中文"})

    for fixture_id, data, encoding, bom in [
        ("ENC-INVALID-UTF8", b"valid\nbroken:\xff\xfe\xc3(\n", "utf-8", b""),
        ("ENC-INVALID-UTF16LE", b"\xff\xfe" + "valid\r\n".encode("utf-16-le") + b"\x3d", "utf-16-le", b"\xff\xfe"),
    ]:
        path = sample_dir / (fixture_id + ".bin")
        temp = path.with_name(path.name + ".tmp")
        temp.write_bytes(data)
        os.replace(temp, path)
        files.append({
            "id": fixture_id,
            "path": path.relative_to(manifest_path.parent).as_posix(),
            "category": "intentional-decoding-error",
            "seed_dependent": False,
            "size_bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "encoding": encoding,
            "expected_strict_decode_valid": False,
            "bom_hex": bom.hex(),
            "bom_bytes": len(bom),
            "line_count": None,
            "max_line_bytes": None,
            "max_line_unicode_scalars": None,
            "structure": {"semantic_line_statistics": "undefined until decoding policy is chosen", "expected_behavior": "report decoding failure; never silently overwrite replacement characters"},
        })

    small("REGEX-ADV", "a" * (32 * KIB) + "b", metadata={
        "patterns": ["(a+)+$", "(?:a|aa)+$"],
        "expected_behavior": "correct bounded completion or explicit limit/timeout; never freeze",
        "engine_results_measured": False,
    })
    small("REGEX-CASES", "banana\nb ab\nbegin\n中文\nend\nprefixABC\n", metadata={
        "patterns": ["(?=a)", "(a)?b", "(?s)begin.*end", "(?<=prefix)[A-Z]{3}", "(["],
        "invalid_pattern": "([",
        "replacement_cases": ["$0", "$&", "$1", "${missing}", "$$"],
        "engine_results_measured": False,
    })

    if args.profile in ("standard", "stress"):
        sized_text("TXT-10", 10 * MIB)
        sized_text("TXT-100", 100 * MIB)
        sized_text("ASCII-10", 10 * MIB, True)
        sized_text("ASCII-100", 100 * MIB, True)
        sized_md("MD-10", 10 * MIB)
        sized_md("MD-100-SOURCE", 100 * MIB)
        sized_long("LONG-1M", MIB)
        sized_matches("MATCH-HIGH-10", 10 * MIB)
        sized_matches("MATCH-HIGH-100", 100 * MIB)

    if args.profile == "stress":
        sized_long("LONG-100M", 100 * MIB)
        def mixed_long(writer: FixtureWriter) -> dict:
            writer.write_text("header\n")
            writer.write_text("L" * MIB + "\n")
            remaining = 100 * MIB - writer.size
            # fill_exact expects an initially empty byte count; write a bounded
            # number of complete regular records and an ASCII tail instead.
            complete = 0
            buffered: list[str] = []
            buffered_size = 0
            for record in plain_records(args.seed):
                n = len(record.encode("utf-8"))
                if n > remaining:
                    break
                buffered.append(record)
                buffered_size += n
                remaining -= n
                complete += 1
                if buffered_size >= 64 * KIB:
                    writer.write_text("".join(buffered))
                    buffered.clear()
                    buffered_size = 0
                if remaining == 0:
                    break
            if buffered:
                writer.write_text("".join(buffered))
            writer.write_text("x" * remaining)
            if writer.size != 100 * MIB:
                raise AssertionError("mixed long-line size mismatch")
            return {"exact_target_bytes": 100 * MIB, "long_line_scalars": MIB, "complete_normal_records": complete}
        text_fixture("MIXED-LONG-100M", ".txt", mixed_long, category="mixed-long-line", seed_dependent=True)

    manifest = {
        "schema_version": 1,
        "generator": {
            "name": "texzi-fixtures",
            "version": VERSION,
            "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "python": platform.python_version(),
            "seed_algorithm": "LCG32: state=(1664525*state+1013904223) mod 2^32",
        },
        "profile": args.profile,
        "seed": args.seed,
        "files": files,
        "summary": {"file_count": len(files), "total_bytes": sum(f["size_bytes"] for f in files)},
        "coverage": {
            "generated_ids": [f["id"] for f in files],
            "not_implemented": NOT_IMPLEMENTED,
            "not_generated_in_smoke": "10/100 MiB normal fixtures; use standard",
            "stress_additions": ["LONG-100M", "MIXED-LONG-100M"],
            "windows_performance_measured": False,
            "parser_structure_validated": False,
        },
    }
    manifest_temp = manifest_path.with_name(manifest_path.name + ".tmp")
    manifest_temp.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(manifest_temp, manifest_path)
    print(json.dumps({"manifest": str(manifest_path), "profile": args.profile, **manifest["summary"], "not_implemented": NOT_IMPLEMENTED}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
